/** <tmp>/helmlock (system layer) and <tmp>/acme (workspace layer), siblings on one drive. */
function copyLayers(): { base: string; delivery: string; root: string } {
  const base = mkdtempSync(join(tmpdir(), "hl-layers-"));
  const delivery = join(base, "helmlock");
  const root = join(base, "acme");
  cpSync(join(FIXTURES, "s5-layers", "delivery"), delivery, { recursive: true });
  cpSync(join(FIXTURES, "s5-layers", "knowledge"), root, { recursive: true });
  return { base, delivery, root };
}

test("knowledge repo: system and workspace layers merge (system first) into both hosts' config", () => {
  const { base, delivery, root } = copyLayers();
  try {
    syncHarness(root, delivery);
    const settings = JSON.parse(readFileSync(join(root, ".claude/settings.json"), "utf8"));
    assert.deepEqual(settings.permissions.deny, [
      "Edit(artifacts/**/ticket.toml)",
      "Edit(logs/**)",
      "Edit(secrets/**)",
      "Read(.env)",
      "Read(_work/**)",
      "Read(author.local)",
      "Read(*.local.toml)",
      "Bash(rm -rf:*)",
    ]);
    assert.deepEqual(settings.permissions.ask, ["Bash(git push:*)", "Bash(npm publish:*)"]);
    const hooks = "$CLAUDE_PROJECT_DIR/../helmlock/packages/plugins/harness/hooks";
    const cmds = (ev: string) => (settings.hooks[ev] as { hooks: { command: string }[] }[]).map((g) => g.hooks[0]?.command);
    assert.deepEqual(cmds("SessionStart"), [
      `node "${hooks}/session-start.ts" --host claude -- context --session`,
      `node "${hooks}/session-start.ts" --host claude -- where`,
    ]);
    assert.deepEqual(cmds("PostToolUse"), [`node "${hooks}/post-edit.ts" --host claude -- validate --changed`], "identical hook deduped");
    assert.deepEqual(cmds("Stop"), [
      `node "${hooks}/stop.ts" --host claude --policy ../helmlock/harness/harness.toml --policy harness/harness.toml -- log show`,
    ]);
    const cursor = JSON.parse(readFileSync(join(root, ".cursor/hooks.json"), "utf8"));
    assert.equal(cursor.hooks.afterFileEdit[0].command, `node "../helmlock/packages/plugins/harness/hooks/post-edit.ts" --host cursor -- validate --changed`);
    assert.equal(cursor.hooks.beforeShellExecution, undefined); // opt-in only, see generate.ts
    // mcp: workspace wins on the same name; ignore: union
    assert.deepEqual(JSON.parse(readFileSync(join(root, ".mcp.json"), "utf8")).mcpServers.helmlock.args, ["other.ts"]);
    assert.match(readFileSync(join(root, ".cursorignore"), "utf8"), /\narchive\/\n_work\/\nruns\/\*\*\n$/);
    // Cursor gets the system AGENTS.md (without its block) then the merged rules; README.md is not a rule
    const mdc = readFileSync(join(root, ".cursor/rules/helmlock.mdc"), "utf8");
    assert.match(mdc, /# Fixture system rulebook\n\nSystem gate: GROUND before drafting anything\.\n\n## System core rules\n[\s\S]*## Workspace rules\n/);
    assert.ok(!mdc.includes("old system block") && !mdc.includes("Not a rule"));
    // the knowledge AGENTS.md block carries the merged rules, not the whole system AGENTS.md
    const agents = readFileSync(join(root, "AGENTS.md"), "utf8");
    assert.match(
      agents,
      /^# Fixture knowledge center\n\nHand-written text stays\.\n\n<!-- hl:generated:start -->[\s\S]*## System core rules[\s\S]*## Workspace rules[\s\S]*<!-- hl:generated:end -->\n$/,
    );
    assert.ok(!agents.includes("System gate"));
    assert.ok(syncHarness(root, delivery, { check: true }).every((r) => r.status === "unchanged"));
    // a change in either layer makes --check stale
    const stale = () =>
      syncHarness(root, delivery, { check: true })
        .filter((r) => r.status === "stale")
        .map((r) => r.path);
    writeFileSync(join(delivery, "harness/rules/10-core.md"), "## System core rules\n\n- Changed.\n");
    assert.ok(stale().includes(".claude/settings.json"));
    syncHarness(root, delivery);
    writeFileSync(
      join(root, "harness/harness.toml"),
      readFileSync(join(root, "harness/harness.toml"), "utf8").replace('"secrets/**"', '"secrets/**", "keys/**"'),
    );
    assert.ok(stale().includes(".claude/settings.json"));
    syncHarness(root, delivery);
    writeFileSync(join(delivery, "AGENTS.md"), readFileSync(join(delivery, "AGENTS.md"), "utf8").replace("GROUND", "SURVEY"));
    assert.ok(stale().includes(".cursor/rules/helmlock.mdc"));
  } finally {
    rmSync(base, { recursive: true, force: true });
  }
});

