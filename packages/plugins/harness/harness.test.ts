test("hl harness sync / --check / lint through the verb registry", async () => {
  const ws = await createTestWorkspace({ catalog });
  try {
    cpSync(join(FIXTURES, "s5-harness", "harness"), join(ws.root, "harness"), { recursive: true });
    const check1 = await ws.run("harness sync", { check: true });
    assert.equal(check1.ok, false);
    assert.equal(!check1.ok && check1.error.rule, "harness-stale");
    const sync = await ws.run("harness sync", {});
    assert.ok(sync.ok);
    assert.ok(existsSync(join(ws.root, ".cursor", "hooks.json")));
    const check2 = await ws.run("harness sync", { check: true });
    assert.ok(check2.ok);
    const lint = await ws.run("harness lint", {});
    assert.ok(lint.ok, JSON.stringify(lint));
    const svc = ws.runtime.ctx.get("harness");
    assert.deepEqual(await svc.lint({ root: join(FIXTURES, "s5-lint") }).then((f) => f.filter((x) => x.level === "error").length), 18);
  } finally {
    await ws.cleanup();
  }
});

